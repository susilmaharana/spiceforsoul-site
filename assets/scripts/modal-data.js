function guessImage(name) {
  const exact = (name || '').trim();
  if (exact && window.DISH_INFO[exact] && window.DISH_INFO[exact].img) {
    return window.DISH_INFO[exact].img;
  }

  const slug = exact.toLowerCase();
  const localName = slug.replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
  const candidates = [
    `assets/dishes/${exact}.png`,
    `assets/dishes/${exact}.jpg`,
    `assets/dishes/${localName}.png`,
    `assets/dishes/${localName}.jpg`,
    `assets/hero_kadhaipaneer-1280.jpg`
  ];

  return candidates[0];
}

function openModal(name) {
  const info = window.DISH_INFO[name] || {};
  const modal = document.getElementById('dish-modal');
  const imgEl = document.getElementById('dish-image');
  const titleEl = document.getElementById('dish-title');
  const descEl = document.getElementById('dish-desc');
  const ingEl = document.getElementById('dish-ingredients');
  if (!modal || !imgEl || !titleEl || !descEl || !ingEl) return;

  titleEl.textContent = name;
  imgEl.src = guessImage(name);
  imgEl.onerror = () => {
    imgEl.onerror = null;
    imgEl.src = 'assets/hero_kadhaipaneer-1280.jpg';
  };
  imgEl.alt = name;
  descEl.textContent = info.desc || 'Pure vegetarian/vegan preparation. No onion, no garlic, no eggs. Home-cooked fresh in small batches.';
  ingEl.innerHTML = '';
  const ingredients = info.ing || ['Ingredients vary by batch; always vegetarian, no onion, no garlic, no eggs.'];
  ingredients.forEach(item => {
    const li = document.createElement('li');
    li.textContent = item;
    ingEl.appendChild(li);
  });

  modal.classList.add('show');
  modal.setAttribute('aria-hidden', 'false');
  document.body.style.overflow = 'hidden';
  const closeButton = modal.querySelector('.modal-close');
  if (closeButton) closeButton.focus();
}

function closeModal() {
  const modal = document.getElementById('dish-modal');
  if (!modal) return;
  modal.classList.remove('show');
  modal.setAttribute('aria-hidden', 'true');
  document.body.style.overflow = '';
}

document.addEventListener('click', event => {
  const button = event.target.closest('.dish-btn');
  if (button) {
    event.preventDefault();
    openModal(button.dataset.dish || button.textContent.trim());
    return;
  }
  const row = event.target.closest('.table-wrap tbody tr');
  if (row) {
    const rowButton = row.querySelector('.dish-btn');
    if (rowButton) rowButton.click();
    return;
  }
  if (event.target.closest('[data-close]')) {
    closeModal();
  }
});

document.addEventListener('keydown', event => {
  if ((event.key === 'Enter' || event.key === ' ') && event.target.matches('.table-wrap tbody tr')) {
    event.preventDefault();
    const button = event.target.querySelector('.dish-btn');
    if (button) button.click();
    return;
  }
  if (event.key === 'Escape') closeModal();
});
